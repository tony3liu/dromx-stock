from typing import Annotated

from langgraph.graph import MessagesState
from typing_extensions import TypedDict


# Researcher team state
class InvestDebateState(TypedDict):
    bull_history: Annotated[
        str, "Bullish Conversation history"
    ]  # Bullish Conversation history
    bear_history: Annotated[
        str, "Bearish Conversation history"
    ]  # Bullish Conversation history
    history: Annotated[str, "Conversation history"]  # Conversation history
    current_response: Annotated[str, "Latest response"]  # Last response
    judge_decision: Annotated[str, "Final judge decision"]  # Last response
    count: Annotated[int, "Length of the current conversation"]  # Conversation length


# Risk management team state
class RiskDebateState(TypedDict):
    aggressive_history: Annotated[
        str, "Aggressive Agent's Conversation history"
    ]  # Conversation history
    conservative_history: Annotated[
        str, "Conservative Agent's Conversation history"
    ]  # Conversation history
    neutral_history: Annotated[
        str, "Neutral Agent's Conversation history"
    ]  # Conversation history
    history: Annotated[str, "Conversation history"]  # Conversation history
    latest_speaker: Annotated[str, "Analyst that spoke last"]
    current_aggressive_response: Annotated[
        str, "Latest response by the aggressive analyst"
    ]  # Last response
    current_conservative_response: Annotated[
        str, "Latest response by the conservative analyst"
    ]  # Last response
    current_neutral_response: Annotated[
        str, "Latest response by the neutral analyst"
    ]  # Last response
    judge_decision: Annotated[str, "Judge's decision"]
    count: Annotated[int, "Length of the current conversation"]  # Conversation length


class AgentState(MessagesState):
    company_of_interest: Annotated[str, "Company that we are interested in trading"]
    asset_type: Annotated[str, "Asset type under analysis such as stock or crypto"]
    instrument_context: Annotated[str, "Deterministic ticker identity resolved at run start"]
    instrument_type: Annotated[str, "Instrument framework type: equity/etf/leveraged_etf/inverse_etf"]
    framework_note: Annotated[str, "Type-specific analysis-framework instruction (empty for plain equity)"]
    market_context: Annotated[str, "Move cross-validation: candidate vs benchmark vs peers (market/sector/idiosyncratic)"]
    trade_date: Annotated[str, "What date we are trading at"]

    sender: Annotated[str, "Agent that sent this message"]

    # pre-analysis market-state classification (Regime Detection node)
    regime_report: Annotated[str, "Market-regime classification from the Regime Analyst"]

    # research step
    market_report: Annotated[str, "Report from the Market Analyst"]
    sentiment_report: Annotated[str, "Report from the Sentiment Analyst"]
    news_report: Annotated[
        str, "Report from the News Researcher of current world affairs"
    ]
    fundamentals_report: Annotated[str, "Report from the Fundamentals Researcher"]
    industry_report: Annotated[str, "Report from the Industry & Supply-Chain Analyst"]

    # post-analyst signal fusion (Signal Aggregator node): confidence-weighted
    # consensus + explicit points of disagreement, consumed by the debate layer
    signal_aggregation: Annotated[str, "Aggregated analyst signal from the Signal Aggregator"]

    # post-aggregation attention allocation (Key Question node): the 1–2 pivotal
    # questions the call hinges on, consumed by the debate and the managers
    key_question: Annotated[str, "Pivotal decision questions from the Key Question Analyst"]

    # premise-shift detection (Event Impact node): whether any event re-rates the
    # thesis / whether unanimity rests on incomplete info, consumed by debate + PM
    event_impact: Annotated[str, "Premise-shift assessment from the Event Impact Assessor"]

    # adaptive analysis depth chosen by the Signal Aggregator from how contested /
    # unusual the setup is: Quick Scan / Standard / Deep Dive
    analysis_depth: Annotated[str, "Adaptive analysis depth tier from the Signal Aggregator"]

    # research team — independent parallel reports (no debate). The Growth &
    # Quality and Valuation & Risk analysts each write one report; the Research
    # Manager synthesises both. (Replaces the old Bull⇄Bear debate loop; the
    # investment_debate_state below is kept as an inert shell for back-compat.)
    growth_report: Annotated[str, "Independent report from the Growth & Quality Analyst"]
    risk_report: Annotated[str, "Independent report from the Valuation & Risk Analyst"]

    # researcher team discussion step
    investment_debate_state: Annotated[
        InvestDebateState, "Current state of the debate on if to invest or not"
    ]
    investment_plan: Annotated[str, "Plan generated by the Analyst"]

    trader_investment_plan: Annotated[str, "Plan generated by the Trader"]

    # risk team — independent parallel reports (no debate). Reward / Tail-Risk /
    # Regime specialists each write one report; Risk Consensus reconciles them.
    reward_risk_report: Annotated[str, "Report from the Position Sizing & Reward Specialist"]
    tailrisk_report: Annotated[str, "Report from the Tail Risk & Drawdown Specialist"]
    regime_risk_report: Annotated[str, "Report from the Regime & Macro Context Specialist"]

    # risk management team discussion step
    risk_debate_state: Annotated[
        RiskDebateState, "Current state of the debate on evaluating risk"
    ]
    final_trade_decision: Annotated[str, "Final decision made by the Risk Analysts"]
    risk_consensus: Annotated[str, "Unified stop-loss framework from the Risk Consensus node"]
    forecast_report: Annotated[str, "Time-layered forecast (T+1/T+5/T+20/T+60) from the Forecast Synthesizer"]
    past_context: Annotated[str, "Memory log context injected at run start (same-ticker decisions + cross-ticker lessons)"]
    portfolio_context: Annotated[str, "Pre-trade portfolio-interaction context (correlation + concentration vs current holdings)"]
    position_context: Annotated[str, "The user's existing position IN this name (shares + cost basis → P&L), or a build-from-flat note when none"]

    # === v0.4 agentic pipeline ===
    # Orchestrator's run-specific plan (rendered markdown). Analysts parse it to
    # decide whether to run or noop; PM/KeyQuestion read it for context.
    orchestration_plan: Annotated[str, "Orchestrator's analyst + skill selection plan (rendered markdown)"]
    # DepthController's verdict after SignalAgg + EventImpact.
    depth_decision: Annotated[str, "DepthController verdict: conclude / standard / deep_dive (rendered markdown)"]
    # Event Impact -> DepthController -> Re-Analysis chain.
    trigger_reanalysis: Annotated[bool, "Whether Event Impact flagged a premise-changing event needing re-analysis"]
    reanalysis_targets: Annotated[list[str], "Analyst keys whose reports the Re-Analysis node should re-examine"]
    # Analyst agent-loop telemetry (per analyst key).
    analyst_iterations: Annotated[dict, "Per-analyst tool-call round count {analyst_key: N}"]
    analyst_tool_calls: Annotated[dict, "Per-analyst tool-call log {analyst_key: [tool_name, ...]}"]
